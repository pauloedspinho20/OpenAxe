import type { BlockKind } from '@openaxe/ui'

export type PaletteCategory = 'Neural Amp Modeler' | 'Core' | 'Effects'

export interface KnobControlDef {
  key: string
  label: string
  control: 'knob'
  min: number
  max: number
  step: number
  defaultValue: number
  formatValue: (value: number) => string
  description: string
}

export interface SelectControlDef {
  key: string
  label: string
  control: 'select'
  options: ReadonlyArray<{ value: string; label: string }>
  defaultValue: string
  description: string
}

export type ParamControlDef = KnobControlDef | SelectControlDef

export interface SignalBlockDef {
  kind: BlockKind
  label: string
  category: PaletteCategory
  colorVar: string
  vendor: string
  vendorUrl?: string
  bypassable: boolean
  summary: string
  params: readonly ParamControlDef[]
}

const dB = (v: number) => `${v.toFixed(0)}dB`
const trimDb = (v: number) => {
  if (v <= 0) return '−∞dB'
  const db = 20 * Math.log10(v)
  if (Math.abs(db) < 0.05) return '0.0dB'
  const sign = db > 0 ? '+' : ''
  return `${sign}${db.toFixed(1).replace('-', '−')}dB`
}
const pct = (v: number) => `${Math.round(v * 100)}%`
const pctRaw = (v: number) => `${Math.round(v)}%`
const ms = (v: number) => `${Math.round(v * 1000)}ms`
const msRaw = (v: number) => `${Math.round(v)}ms`
const hz = (v: number) => (v >= 1000 ? `${(v / 1000).toFixed(1)}kHz` : `${Math.round(v)}Hz`)
const hzPrecise = (v: number) => `${v.toFixed(1)}Hz`
const ratio = (v: number) => `${v.toFixed(1)}:1`
const plain = (v: number) => v.toFixed(2)

