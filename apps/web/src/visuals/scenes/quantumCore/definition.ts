const mod = (
  id: string,
  param: string,
  source: Modulation['source'],
  amount: number,
  curve: Modulation['curve'] = 'linear',
  attack = 0,
  release = 0,
): Modulation => ({ id, param, source, amount, curve, attack, release, enabled: true })

const modulations: readonly Modulation[] = [
  // Level: louder playing lights the core up.
  mod('light-vol', 'lightIntensity', 'volume', 0.15, 'ease'),
  mod('light-onset', 'lightIntensity', 'onset', 0.2, 'expo'),
  // Held notes speed up the flight.
  mod('travel-sustain', 'travelRate', 'sustain', 0.1, 'ease', 0.1, 0.4),
  // Bass turns the mirror; grit warps the space.
  mod('mirror-low', 'mirrorSpeed', 'bandLow', 0.08, 'ease', 0.02, 0.3),
  mod('detail-grit', 'detailAmount', 'grit', -0.15, 'ease'),
  mod('scale-high', 'detailScale', 'bandHigh', 0.05, 'ease'),
  // Pitch: note -> spectral hue.
  mod('hue-note', 'hueShift', 'pitchClass', 1, 'linear', 0.05),
]

